package sa.mosque.display;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

/** Actual matcher fixtures; no Android APIs, device detection, sockets, or package operations. */
public final class DeviceProfilesTest {
    private static int checks;
    private static void check(boolean value,String text){checks++;if(!value)throw new AssertionError(text);}
    private static DeviceProfiles.Profile p(String id,String brand,String model,Integer os){
        return new DeviceProfiles.Profile(id,brand,model,os,Arrays.asList("com.example.app"));
    }
    private static void no(List<DeviceProfiles.Profile> rows,String maker,String brand,String model,int os,String reason){
        DeviceProfiles.Match actual=DeviceProfiles.select(rows,maker,brand,model,os);
        check(actual.profile==null&&reason.equals(actual.reason),reason+" got "+actual.reason);
    }
    public static void main(String[] args)throws Exception{
        DeviceProfiles.Profile sony=p("sony-x90","Sony","x90",11),tcl=p("tcl-x90","TCL","x90",11);
        List<DeviceProfiles.Profile> rows=Arrays.asList(sony,tcl);
        check(DeviceProfiles.select(rows,"TCL","tcl","X-90",11).profile==tcl,"Exact normalized brand/model selects correct brand");
        check(DeviceProfiles.select(rows,"SONY","Sony","x90",11).profile==sony,"Same model on different brand remains distinct");
        check(DeviceProfiles.select(rows,"","Sony","x90",11).profile==sony,"Explicit brand supplies missing manufacturer");
        check(DeviceProfiles.select(rows,"Sony","","x90",11).profile==sony,"Manufacturer supplies missing brand");
        check(DeviceProfiles.select(rows,"ＳＯＮＹ","Sony","Ｘ９０",11).profile==sony,"NFKC representation normalization");
        no(rows,"Sony","TCL","x90",11,"OEM_CONFLICT");
        no(rows,"Sony","Sony","x900",11,"NO_EXACT_MODEL");
        no(rows,"Sony","Sony","x90 pro",11,"NO_EXACT_MODEL");
        no(rows,"Sony","Sony","x90",12,"ANDROID_VERSION_MISMATCH");
        no(rows,"Sony","Sony","x90",0,"MISSING_ANDROID_VERSION");
        no(rows,"","","x90",11,"MISSING_OEM");
        no(rows,"Sony","Sony","",11,"MISSING_MODEL");
        no(null,"Sony","Sony","x90",11,"NO_PROFILES");
        DeviceProfiles.Profile base=p("tcl-beyondtv","TCL","beyondtv",9),variant=p("tcl-beyondtv-rt2851","TCL","beyondtv-rt2851",11);
        no(Arrays.asList(base,variant),"TCL","TCL","BeyondTV",9,"AMBIGUOUS_VARIANT");
        check(DeviceProfiles.select(Arrays.asList(base,variant),"TCL","TCL","BeyondTV-RT2851",11).profile==variant,"Variant cannot be inferred from bare model");
        check(DeviceProfiles.select(Arrays.asList(base,p("tcl-beyondtv-other","Sony","other",9)),"TCL","TCL","BeyondTV",9).profile==base,"Different-brand variant cannot affect OEM match");
        no(Arrays.asList(p("sony-unknown","Sony","unknown",null)),"Sony","Sony","unknown",11,"MISSING_PROFILE_ANDROID_VERSION");
        no(Arrays.asList(sony,p("sony-other","Sony","x90",11)),"Sony","Sony","x90",11,"AMBIGUOUS_MODEL");
        check(DeviceProfiles.select(Arrays.asList(sony,p("sony-other","Sony","x90",12)),"Sony","Sony","x90",12).profile.osMajor==12,"OS must match chosen record");
        ArrayList<String> packages=new ArrayList<>();packages.add("com.example.app");
        DeviceProfiles.Profile copy=new DeviceProfiles.Profile("sony-copy","Sony","copy",11,packages);packages.clear();
        check(copy.packages.size()==1,"Defensive package snapshot");
        try{copy.packages.clear();throw new AssertionError("Mutable packages");}catch(UnsupportedOperationException expected){checks++;}
        if(args.length!=1)throw new IllegalArgumentException("Catalogue TSV generated by the Node harness is required.");
        List<DeviceProfiles.Profile> actual=new ArrayList<>();
        for(String line:Files.readAllLines(Paths.get(args[0]),StandardCharsets.UTF_8)){
            String[] fields=line.split("\t",-1);if(fields.length!=4)throw new IllegalArgumentException("Invalid fixture fields.");
            actual.add(p(fields[0],fields[1],fields[2],fields[3].equals("null")?null:Integer.valueOf(fields[3])));
        }
        check(actual.size()==416,"Actual shipped catalogue fixture count");
        no(actual,"TCL","TCL","BeyondTV",9,"AMBIGUOUS_VARIANT");
        no(actual,"TCL","TCL","BeyondTV",11,"AMBIGUOUS_VARIANT");
        no(actual,"TCL","TCL","BeyondTV2",11,"NO_EXACT_MODEL");
        no(actual,"TCL","TCL","65Q550G",11,"MISSING_PROFILE_ANDROID_VERSION");
        DeviceProfiles.Match exact=DeviceProfiles.select(actual,"TCL","TCL","BeyondTV-RT2851",9);
        check(exact.profile!=null&&exact.profile.id.equals("tcl-beyondtv-rt2851"),"Pinned exact variant record");
        System.out.println("{\"passed\":"+checks+",\"failed\":0}");
    }
}
